-- Entirely censored text and zero recipients still count as one message.
-- FILTER constructs an empty typed array; the SQL ARRAY[] literal is unsupported.
INSERT INTO CHAT_DELIVERIES (SENDER_ID, MESSAGE, RECIPIENT_IDS)
VALUES ('alice', STRUCT(MESSAGE_ID := 'm-5', SENDER_ID := 'alice', TEXT := '***'), FILTER(ARRAY['unused'], X => false));
ASSERT VALUES CHAT_MESSAGE_COUNTS (SENDER_ID, MESSAGE_COUNT) VALUES ('alice', 1);
ASSERT VALUES CHAT_USER_STATISTICS (SENDER_ID, MESSAGE_COUNT, UNIQUE_RECIPIENT_COUNT) VALUES ('alice', 1, 0);

