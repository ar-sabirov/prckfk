-- These are final delivery decisions; censorship and blocking are upstream.
-- ASSERT VALUES consumes output records in order, including intermediate joins.
INSERT INTO CHAT_DELIVERIES (SENDER_ID, MESSAGE, RECIPIENT_IDS)
