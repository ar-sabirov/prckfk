ASSERT VALUES CHAT_RECIPIENT_COUNTS (SENDER_ID, UNIQUE_RECIPIENT_COUNT) VALUES ('bob', 1);
ASSERT VALUES CHAT_USER_STATISTICS (SENDER_ID, MESSAGE_COUNT, UNIQUE_RECIPIENT_COUNT) VALUES ('bob', 1, 0);
ASSERT VALUES CHAT_USER_STATISTICS (SENDER_ID, MESSAGE_COUNT, UNIQUE_RECIPIENT_COUNT) VALUES ('bob', 1, 1);

